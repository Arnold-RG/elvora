# ---------------- config ----------------
API_KEY = (os.environ.get("GEMINI_API_KEY") or "").strip()
MODELS = [m.strip() for m in os.environ.get("GEMINI_MODELS", "gemini-3.5-flash-lite,gemini-3.1-flash-lite").split(",") if m.strip()]
DEV = os.environ.get("ELVORA_DEV") == "1"
DEV_ORIGINS = ["http://localhost:8080", "http://127.0.0.1:8080"]
ALLOWED_ORIGINS = [o.strip() for o in os.environ.get("ALLOWED_ORIGINS", "https://elvora-app-preview.onrender.com").split(",")
                   if o.strip() and (DEV or not o.strip().startswith(("http://localhost", "http://127.0.0.1")))]
if DEV:
    ALLOWED_ORIGINS += [o for o in DEV_ORIGINS if o not in ALLOWED_ORIGINS]
# Conservative in-memory caps (free tier allows 15 RPM / 500 RPD per model)
PER_IP_PER_MIN = int(os.environ.get("RATE_PER_IP_PER_MIN", "5"))
PER_IP_PER_DAY = int(os.environ.get("RATE_PER_IP_PER_DAY", "60"))
PER_SESSION_PER_MIN = int(os.environ.get("RATE_PER_SESSION_PER_MIN", "5"))
GLOBAL_PER_MIN = int(os.environ.get("RATE_GLOBAL_PER_MIN", "10"))
GLOBAL_PER_DAY = int(os.environ.get("RATE_GLOBAL_PER_DAY", "300"))
SESSION_PER_IP_PER_MIN = int(os.environ.get("RATE_SESSION_PER_IP_PER_MIN", "6"))
SESSION_TTL_S = int(os.environ.get("SESSION_TTL_S", "1800"))
SESSION_SECRET_RAW = (os.environ.get("ELVORA_SESSION_SECRET") or "").strip().encode()
MIN_SECRET_BYTES = 32
# Fail closed: a missing or short secret disables /api/session and /api/coach (health still answers).
SESSION_SECRET = SESSION_SECRET_RAW if len(SESSION_SECRET_RAW) >= MIN_SECRET_BYTES else b""
UPSTREAM_TIMEOUT = float(os.environ.get("UPSTREAM_TIMEOUT_S", "12"))
MAX_BODY = 4096
PACIFIC = ZoneInfo("America/Los_Angeles")  # Gemini daily quota resets at Pacific midnight
SESSION_HEADER = "x-elvora-session"

_client: Optional[httpx.AsyncClient] = None


@asynccontextmanager
async def lifespan(_app):
    global _client
    _client = httpx.AsyncClient(timeout=httpx.Timeout(UPSTREAM_TIMEOUT, connect=5.0))
    if SESSION_SECRET_RAW and not SESSION_SECRET:
        log.error("ELVORA_SESSION_SECRET is shorter than %d bytes; session and coach endpoints are disabled", MIN_SECRET_BYTES)
    log.info("coach api up; key configured=%s session secret ok=%s models=%s origins=%d dev=%s",
             bool(API_KEY), bool(SESSION_SECRET), MODELS, len(ALLOWED_ORIGINS), DEV)
    yield
    await _client.aclose()


app = FastAPI(title="Elvora coach API", docs_url=None, redoc_url=None, openapi_url=None, lifespan=lifespan)
app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_methods=["POST", "GET", "OPTIONS"],
    allow_headers=["content-type", SESSION_HEADER],
    max_age=600,
)

