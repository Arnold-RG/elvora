"""Elvora coach API: one endpoint that turns a user's question plus a small
context block into a short coaching reply from Google Gemini.

Security notes
- GEMINI_API_KEY comes from the environment only; it is sent in a request
  header (never a URL) and never logged or returned.
- Request bodies are size-limited and validated; user text is never logged.
- Every /api/* request must carry an allowed Origin (a missing Origin is
  rejected). Localhost origins are only accepted when ELVORA_DEV=1.
- /api/coach also needs a short-lived HMAC-signed session token from
  POST /api/session (Origin-checked, rate-limited). The signing secret is
  ELVORA_SESSION_SECRET (generated by Render, never logged or returned).
- The client IP used for rate limits comes from Cloudflare's CF-Connecting-IP
  (set by the edge, overwrites anything the client sends), else the rightmost
  public X-Forwarded-For hop. A client-supplied first XFF hop is never trusted.
- Bodies are capped at 4 KB while streaming, before any Gemini call.
- Rate limits stay well under the Gemini free tier (per IP, per session,
  global per minute, per day). They are in memory, per process: persisting
  them across restarts or instances would need Render Key Value.
- Any upstream problem returns {"ok": false, "fallback": true} so the app can
  answer with its built-in rule-based coach instead.
"""
